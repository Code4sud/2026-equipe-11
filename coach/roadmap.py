"""« Ton chemin » : how to get from where the young person is now to a job, and which
course suits them best. Everything is computed from the open data (ONISEP courses,
ROME mobility), never generated by the LLM, so every step can be traced to a source."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import date

from rapidfuzz import fuzz

from coach.text import normalize

# where the young person is now -> index in STAGES (None = not said)
SITUATIONS = {
    "Au collège (4e / 3e)": 0,
    "Au lycée ou en CAP": 1,
    "J'ai le bac": 2,
    "Je fais des études après le bac": 3,
    "Je préfère ne pas dire": None,
}
# (label, LHEO entry codes) : the moment you can start the course
STAGES = [
    ("Après la 3e", {"1", "12"}),
    ("Après une 2de ou un CAP", {"13"}),
    ("Après le bac", {"14"}),
    ("Après un bac + 2 ou plus", {"15", "16", "17"}),
]
LEVEL_RANK = {"CAP ou équivalent": 3, "CAP ou équivalent + 1 an": 3.5, "bac ou équivalent": 4,
              "bac + 1": 5, "bac + 2": 6, "bac + 3": 7, "bac + 4": 8, "bac + 5": 9, "bac + 6": 10}
BAC_BRIDGE = {0: ("Obtenir le bac (général, technologique ou professionnel)", 3),
              1: ("Terminer le lycée et obtenir le bac", 2)}


def years(duration: str) -> int:
    m = re.match(r"(\d+)", duration or "")
    return int(m.group(1)) if m else 0


def stage_of(f: dict) -> int:
    for i, (_, codes) in enumerate(STAGES):
        if f["entry_code"] in codes:
            return i
    # entry not given: infer it from the level reached
    rank = LEVEL_RANK.get(f["level"], 4)
    return 0 if rank <= 4 else 2 if rank <= 7 else 3


@dataclass
class Diploma:
    """One diploma (e.g. « diplôme d'État d'infirmier ») and all the schools teaching it."""
    title: str
    kind: str
    level: str
    duration: str
    stage: int
    no_bac: bool
    rncp: bool
    schools: list[dict] = field(default_factory=list)  # trainings, nearest first
    variants: list[str] = field(default_factory=list)  # mentions / options

    @property
    def nearest(self) -> dict:
        return self.schools[0]

    @property
    def n_public(self) -> int:
        return sum(1 for s in self.schools if s["status"] == "public")

    @property
    def boarding(self) -> bool:
        return any("internat" in (s.get("housing") or "") for s in self.schools)


VARIANT = re.compile(r"\s+(mention|option|parcours|spécialité)\s+", re.IGNORECASE)


def diplomas(trainings: list[dict]) -> list[Diploma]:
    """Group the trainings of a job by diploma (mentions and options merged), from the
    earliest entry to the latest."""
    by_title: dict[str, Diploma] = {}
    for f in trainings:
        parts = VARIANT.split(f["title"], maxsplit=1)
        base = parts[0].strip()
        d = by_title.get(base)
        if d is None:
            d = by_title[base] = Diploma(
                base, f["diploma_short"] or f["diploma_type"], f["level"],
                f["duration"], stage_of(f), f["no_bac"], bool(f["rncp"]))
        if len(parts) == 3 and f["title"] not in d.variants:
            d.variants.append(f["title"])
        d.schools.append(f)
    return sorted(by_title.values(),
                  key=lambda d: (d.stage, LEVEL_RANK.get(d.level, 0), -len(d.schools)))


def relevance(job: str, title: str) -> int:
    """100 when the diploma is named after the job (« CAP boulanger » for Boulanger)."""
    return int(fuzz.partial_ratio(normalize(job).split()[0], normalize(title)))


@dataclass
class Step:
    title: str
    detail: str
    years: int = 0
    url: str | None = None
    kind: str = "course"      # "start" | "bridge" | "course" | "job"
    facts: list[str] = field(default_factory=list)   # short chips
    lines: list[str] = field(default_factory=list)   # one-line extras
    when: str = ""                                   # « sept. 2027 → juin 2029 »


@dataclass
class Route:
    name: str
    steps: list[Step]
    note: str = ""
    plus_experience: bool = False

    @property
    def duration_text(self) -> str:
        n = self.total_years
        txt = f"{n} an{'s' if n > 1 else ''} de formation" if n else "durée non précisée"
        return ("au moins " + txt + " + de l'expérience") if self.plus_experience else "≈ " + txt

    @property
    def total_years(self) -> int:
        return sum(s.years for s in self.steps)

    ends: str = ""  # « juin 2029 » if started at the next rentrée


def next_rentree(today: date | None = None) -> int:
    today = today or date.today()
    return today.year if today.month < 9 else today.year + 1


def timeline(r: Route, start_year: int) -> None:
    """Indicative calendar: each step with a duration starts in September, ends in June."""
    y = start_year
    for s in r.steps:
        if s.years:
            s.when = f"sept. {y} → juin {y + s.years}"
            y += s.years
    if y > start_year:
        r.ends = f"juin {y}"


def _course_step(d: Diploma, situation: int | None = None) -> Step:
    n = d.nearest
    where = f"{len(d.schools)} établissement(s) en Région Sud"
    if n.get("distance_km") is not None:
        where += f", le plus proche à {n['city']} ({n['distance_km']:.0f} km)"
    detail = " · ".join(x for x in (d.kind, d.duration) if x)
    facts = [f"entrée : {n['entry']}"] if n.get("entry") else []
    if situation is not None and d.stage <= situation:
        facts.append("✓ tu as le niveau pour y entrer")
    if d.no_bac:
        facts.append("sans le bac")
    if d.level:
        facts.append(f"tu obtiens : {d.level}")
    cert = n.get("cert_level", "")
    if d.rncp and cert.startswith("niveau"):
        facts.append(f"reconnu par l'État ({cert})")
    facts.append(f"{len(d.schools)} établ. dont {d.n_public} public{'s' if d.n_public > 1 else ''}")
    if d.boarding:
        facts.append("🏠 internat possible")
    lines = []
    if n.get("distance_km") is not None:
        lines.append(f"📍 Le plus proche : {n['school']}, {n['city']} ({n['distance_km']:.0f} km)")
    if len(d.variants) > 1:
        lines.append(f"{len(d.variants)} spécialités possibles")
    return Step(d.title, f"{detail}  \n{where}", years(d.duration), n["url"],
                facts=facts, lines=lines)


def routes(job: str, dips: list[Diploma], situation: int | None,
           detours: list[tuple[str, list[Diploma]]],
           start_year: int | None = None) -> list[Route]:
    """The main route from the young person's situation, plus a no-bac route if any."""
    start = situation if situation is not None else 0
    you = Step("Toi aujourd'hui", next(k for k, v in SITUATIONS.items() if v == situation)
               if situation is not None else "ta situation (non précisée)", kind="start")
    goal = Step(job, "le métier", kind="job")
    out: list[Route] = []

    reachable = [d for d in dips if d.stage >= start] or dips
    if reachable:
        # the course you can enter soonest; at equal entry, the shortest and most offered
        main = min(reachable, key=lambda d: (relevance(job, d.title) < 80, d.stage,
                                             years(d.duration) or 9, -len(d.schools)))
        steps = [you]
        if situation is not None and main.stage >= 2 and start < 2:
            title, y = BAC_BRIDGE[start]
            steps.append(Step(title, "étape obligatoire pour cette formation", y, kind="bridge",
                              lines=["Au lycée général, technologique ou professionnel."]))
        if situation is not None and main.stage == 3 and start < 3:
            steps.append(Step("Faire des études après le bac (bac + 2 ou plus)",
                              f"demandé pour entrer en « {main.title} »", 2, kind="bridge"))
        steps += [_course_step(main, situation), goal]
        out.append(Route("Le chemin le plus direct pour toi", steps))

    no_bac = [d for d in dips if d.no_bac]
    if situation in (0, 1, None) and dips and not no_bac and detours:
        code_label, ddips = detours[0]
        d = ddips[0]
        out.append(Route(
            "Une passerelle sans le bac",
            [you, _course_step(d, situation),
             Step(code_label, "un premier métier accessible sans le bac", kind="job"),
             Step(f"Évoluer vers {job}", "avec de l'expérience, souvent via une sélection "
                  "ou une formation complémentaire", kind="bridge"), goal],
            note=f"France Travail (ROME) indique la mobilité « {code_label} → {job} ». "
                 "Les conditions exactes (expérience, concours) sont à vérifier avec un "
                 "conseiller.", plus_experience=True))
    elif situation in (0, 1, None) and no_bac and out and not out[0].steps[1].kind == "course":
        d = min(no_bac, key=lambda d: (relevance(job, d.title) < 80, years(d.duration) or 9,
                                       -len(d.schools)))
        out.append(Route("Sans passer par le bac", [you, _course_step(d, situation), goal]))
    for r in out:
        timeline(r, start_year or next_rentree())
    return out


# --------------------------------------------------------------------- ranking
PREFS = {
    "court": "Des études courtes",
    "proche": "Rester près de chez moi",
    "public": "Le public (gratuit ou peu cher)",
    "internat": "Un internat possible",
}


def rank(trainings: list[dict], situation: int | None, prefs: set[str],
         has_location: bool, job: str = "") -> list[tuple[int, list[str], dict]]:
    """Score every school offer for this young person, with the reasons in plain words."""
    out = []
    for f in trainings:
        score, why = 0, []
        if job and relevance(job, f["title"]) >= 80:
            score += 2
            why.append("le diplôme du métier")
        st = stage_of(f)
        if situation is not None:
            if st == situation or (situation >= 2 and st == 2):
                score += 3
                why.append("tu peux y entrer maintenant")
            elif st < situation:
                score += 1
            else:
                score -= 1
        if f["no_bac"] and situation in (0, 1):
            score += 2
            why.append("sans le bac")
        d = f.get("distance_km")
        if has_location and d is not None:
            w = 2 if "proche" in prefs else 1
            pts = 3 if d < 15 else 2 if d < 40 else 1 if d < 80 else 0
            score += pts * w
            if d < 40:
                why.append(f"à {d:.0f} km")
            elif "internat" in (f.get("housing") or ""):
                score += 1 + ("internat" in prefs)
                why.append("internat possible")
        elif "internat" in prefs and "internat" in (f.get("housing") or ""):
            score += 2
            why.append("internat possible")
        if f["status"] == "public":
            score += 2 * (1 + ("public" in prefs))
            why.append("public")
        elif f["status"] == "privé sous contrat":
            score += 1
        if f["rncp"]:
            score += 1
            why.append("diplôme reconnu (RNCP)")
        y = years(f["duration"])
        if "court" in prefs and y:
            score += 3 if y <= 2 else 1 if y <= 3 else 0
            if y <= 2:
                why.append(f"court ({f['duration']})")
        out.append((score, why, f))
    out.sort(key=lambda t: (-t[0], t[2].get("distance_km") or 999))
    return out
